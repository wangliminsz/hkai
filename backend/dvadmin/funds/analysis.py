def report_slug(fund: dict) -> str:
    slug = re.sub(r'[\\/:*?"<>|\r\n\t ]+', "-", str(fund.get("productName") or "fund")).strip(" -")
    return slug[:80] or "fund"


def render_report_html(lot: str, label: str, fund: dict, md_text: str) -> str:
    safe_md = (md_text or "").replace("<", "&lt;")
    body = _md.markdown(safe_md, extensions=["tables", "fenced_code", "nl2br", "sane_lists"], output_format="html")
    return _REPORT_TEMPLATE.format(
        css=_REPORT_CSS,
        topbar=f"{escape(str(lot))} &middot; {escape(str(label))}",
        title=escape(str(fund["productName"])),
        subtitle=escape(f"{fund.get('title', '')}，第{fund.get('rank', '')}名"),
        rank_badge=f"第{escape(str(fund.get('rank', '')))}名",
        fund_name=escape(str(fund["productName"])),
        return_val=f"回报率 {fund.get('returnValue', '')}%",
        body_html=body,
        generated=datetime.now().strftime("%Y-%m-%d %H:%M"),
    )


def _report_dir() -> Path:
    d = getattr(settings, "FUND_REPORT_DIR", "") or ""
    return Path(d) if d else Path(settings.BASE_DIR) / "fund_reports"


def publish_report(lot: str, fund: dict, html_text: str) -> str | None:
    """Write report locally + archive to COS; return the public URL (or None)."""
    safe_lot = re.sub(r"[^0-9A-Za-z_-]+", "-", str(lot or "lot")).strip("-") or "lot"
    name = f"{report_slug(fund)}—{fund.get('rank', '')}.html"
    path = _report_dir() / safe_lot / name
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(html_text, encoding="utf-8")
    except Exception as exc:  # noqa: BLE001
        logger.warning("[ANALYSIS] local report write failed: %s", exc)

    try:
        from dvadmin.cards import cos
        if cos.enabled():
            prefix = (getattr(settings, "FUND_REPORT_COS_PREFIX", "reports/") or "reports/").strip("/")
            cos.upload_bytes(f"{safe_lot}/{name}", html_text.encode("utf-8"),
                             "text/html; charset=utf-8", prefix=prefix, disposition="inline")
    except Exception as exc:  # noqa: BLE001
        logger.warning("[ANALYSIS] COS report upload failed: %s", exc)

    base = (getattr(settings, "NEWS_HTML_BASE", "") or "").rstrip("/")
    if base and path.exists():
        from urllib.parse import quote
        return f"{base}/api/funds/report/{safe_lot}/{quote(name)}"
    return None


def build_analysis_card(fund: dict, html_url: str | None) -> dict:
    pos = int(fund["rank"]) - 1
    title = f"{fund.get('title', '')}，{ORDINALS[pos]}"
    actions = []
    if html_url:
        actions.append({"tag": "button", "text": {"tag": "plain_text", "content": "查看完整分析"},
                        "type": "primary", "url": html_url})
    if fund.get("fund_sheet"):
        actions.append({"tag": "button", "text": {"tag": "plain_text", "content": "基金简报"},
                        "type": "default", "url": fund["fund_sheet"]})
    elements: list[dict] = [
        {"tag": "div", "text": {"tag": "lark_md",
                                "content": f"**{fund['productName']}**\n回报率 {fund.get('returnValue', '')}%"}},
        {"tag": "hr"},
    ]
    if actions:
        elements.append({"tag": "action", "actions": actions})
    elements.append({"tag": "note", "elements": [
        {"tag": "plain_text", "content": f"更多基金信息请访问 {_opt('HKFUND_APP_HOMEPAGE', 'https://hkfund.favor100.site')}"}
    ]})
    return {
        "config": {"wide_screen_mode": True},
        "header": {"title": {"tag": "plain_text", "content": title[:148]}, "template": "turquoise"},
        "elements": elements,
    }
